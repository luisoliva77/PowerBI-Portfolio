SELECT F.NOME AS FUNCIONARIO
FROM FUNCIONARIO F
INNER JOIN SALARIO S
ON F.IDFUNCIONARIO = S.ID_FUNCIONARIO
WHERE S.DATA_FIM IS NULL AND S.VALOR  > (SELECT AVG(VALOR) FROM SALARIO WHERE DATA_FIM IS NULL)
GROUP BY F.NOME
GO

