/* CTE PARA QUANTIDADE DE FALTAS POR FUNCIONARIO
E DEPOIS TRAGA FUNCIONARIOS COM MAIS DE 3 FALTAS */

WITH QTD_FALTAS AS(
	SELECT F.NOME AS FUNCIONARIO, COUNT(ID_FUNCIONARIO) AS QTD_FALTA
	FROM FUNCIONARIO F
	LEFT JOIN FALTA FA
	ON F.IDFUNCIONARIO = FA.ID_FUNCIONARIO
	GROUP BY F.NOME

)

SELECT FUNCIONARIO,QTD_FALTA
FROM QTD_FALTAS
WHERE QTD_FALTA > 1
GO

/* Liste os funcionários que possuem: 
