SELECT NOME, VALOR
FROM FUNCIONARIO F
INNER JOIN SALARIO S
ON F.IDFUNCIONARIO = S.ID_FUNCIONARIO
WHERE VALOR = (SELECT MAX(VALOR) FROM SALARIO WHERE DATA_FIM IS NULL)
GO

/* Liste funcionários que:
possuem mais faltas do que a média de faltas da empresa. */

SELECT F.NOME AS FUNCIONARIO
FROM FUNCIONARIO F
LEFT JOIN FALTA FA
ON F.IDFUNCIONARIO = FA.ID_FUNCIONARIO
GROUP BY F.NOME
HAVING COUNT(FA.IDFALTA) > ( SELECT AVG(QTD_FALTAS)
									FROM ( SELECT COUNT(*) AS QTD_FALTAS
										   FROM FALTA
										   GROUP BY ID_FUNCIONARIO)
										   AS MEDIA_FALTA
)										   							
GO

/* Crie uma CTE com: Nome, Departamento, Salário atual
Depois: Mostre apenas o maior salário de cada departamento. */

WITH FUNCIO_INFO AS(
SELECT F.NOME AS FUNCIONARIO, D.NOME_DEPART AS DEPARTAMENTO, S.VALOR AS SALARIO_ATUAL
FROM FUNCIONARIO F
INNER JOIN DEPARTAMENTO D
ON F.ID_DEPARTAMENTO = D.IDDEPARTAMENTO
INNER JOIN SALARIO S
ON F.IDFUNCIONARIO = S.ID_FUNCIONARIO
