/* CTE QUE MOSTRE NOME,CARGO E SALARIO 
ATUAL E DEPOIS TRAZER FUNCIONARIOS QUE GANHAM MAIS DE 4K */

WITH FUNCIONARIO_INFO AS(
	SELECT F.NOME AS FUNCIONARIO,C.NOME_CARGO AS CARGO,S.VALOR AS SALARIO
	FROM FUNCIONARIO F
